import 'package:flutter/material.dart';

/// Adult aphasia pack content (Tamil + English), organised by the classic
/// aphasia therapy hierarchy. Levels 1–3 match the intake start level:
/// 1 = single words and over-learned series, 2 = words and short phrases,
/// 3 = sentences.
///
/// Written for adults after a stroke: everyday, respectful, no cartoons.
/// Tamil targets are spoken Tamil where people say it that way (தண்ணி
/// வேணும், not தண்ணீர் வேண்டும்) — phone speech recognition and the Tamil
/// scoring server transcribe spoken Tamil — with the written form as an
/// accepted alternate. Pictures are the original Aphora photos
/// (`assets/images/questions/`) or plain Material icons.
///
/// Integrity (unique ids, en + ta everywhere, every level filled for every
/// task, ≥ 40 naming pictures) is checked by `test/aphasia_pack_test.dart`.
enum AphasiaTask {
  /// Counting, days, months, greetings — over-learned series said along.
  automatic,

  /// Listen and repeat: words → phrases → sentences.
  repetition,

  /// Picture naming with the cueing ladder (meaning → first sound → word).
  naming,

  /// Say the missing word at the end of a sentence.
  completion,

  /// Words and phrases for daily needs.
  functional,

  /// Slow, exaggerated speech, part by part (for slurred speech).
  clearSpeech,
}

class AphasiaEntry {
  /// An over-learned series. [glossEn] is the meaning shown in Tamil mode
  /// when [en] is not a translation of [ta].
  const AphasiaEntry.automatic(this.id, this.level, this.en, this.ta,
      {this.enAlt = const [], this.taAlt = const [], this.glossEn})
      : task = AphasiaTask.automatic,
        cueEn = null,
        cueTa = null,
        promptEn = null,
        promptTa = null,
        category = null,
        image = null,
        icon = null;

  const AphasiaEntry.repetition(this.id, this.level, this.en, this.ta,
      {this.enAlt = const [], this.taAlt = const []})
      : task = AphasiaTask.repetition,
        cueEn = null,
        cueTa = null,
        promptEn = null,
        promptTa = null,
        glossEn = null,
        category = null,
        image = null,
        icon = null;

  /// A picture to name: a photo ([image]) or an [icon]. [cueEn]/[cueTa]
  /// describe it without saying it — the first hint, and the question in
  /// harder Picture match rounds.
  const AphasiaEntry.naming(this.id, this.level, this.en, this.ta, this.cueEn,
      this.cueTa, this.category,
      {this.image, this.icon, this.enAlt = const [], this.taAlt = const []})
      : task = AphasiaTask.naming,
        promptEn = null,
        promptTa = null,
        glossEn = null;

  /// [promptEn]/[promptTa] contain `___` where [en]/[ta] goes.
  const AphasiaEntry.completion(this.id, this.level, this.promptEn, this.en,
      this.promptTa, this.ta, this.cueEn, this.cueTa,
      {this.enAlt = const [], this.taAlt = const []})
      : task = AphasiaTask.completion,
        glossEn = null,
        category = null,
        image = null,
        icon = null;

  const AphasiaEntry.functional(this.id, this.level, this.en, this.ta,
      {this.enAlt = const [], this.taAlt = const []})
      : task = AphasiaTask.functional,
        cueEn = null,
        cueTa = null,
        promptEn = null,
        promptTa = null,
        glossEn = null,
        category = null,
        image = null,
        icon = null;

  /// [promptEn]/[promptTa] split the target into parts: ` · ` between
  /// syllables of a word, ` | ` between pauses in a phrase.
  const AphasiaEntry.clearSpeech(this.id, this.level, this.promptEn, this.en,
      this.promptTa, this.ta, {this.enAlt = const [], this.taAlt = const []})
      : task = AphasiaTask.clearSpeech,
        cueEn = null,
        cueTa = null,
        glossEn = null,
        category = null,
        image = null,
        icon = null;

  final AphasiaTask task;

  /// Unique within the task.
  final String id;

  /// 1–3.
  final int level;
  final String en;
  final String ta;
  final List<String> enAlt;
  final List<String> taAlt;
  final String? cueEn;
  final String? cueTa;
  final String? promptEn;
  final String? promptTa;
  final String? glossEn;
  final String? category;
  final String? image;
  final IconData? icon;

  String get picturePath => 'assets/images/questions/$image';
}

